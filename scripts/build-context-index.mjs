#!/usr/bin/env node
// Generates context/decisions/INDEX.md from context/decisions/*.md (CONTRACTS.md 5.1).
// Nobody edits the index by hand: two sessions appending to one shared file is what broke it before.
// A decision is a new file (npm run decision:new); this script rebuilds the list from the files, so it
// is idempotent and any number of sessions converge on the same result.
//
//   npm run context:index            rewrite context/decisions/INDEX.md
//   node scripts/build-context-index.mjs --check   exit 1 if INDEX.md is out of date, or a dated entry
//                                                 was appended to CONTEXT.md instead of being a file
//
// INDEX.md is deliberately not imported by CLAUDE.md: it is a lookup table (about 8k tokens), read or
// grepped when a task needs history, not loaded into every session.

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const MAX_TITLE = 110;
const clean = (s) => s.replace(/[`*]/g, "").replace(/\s+/g, " ").trim();
const shorten = (s) => {
  const t = clean(s).replace(/[.\s]+$/, "");
  if (t.length <= MAX_TITLE) return t;
  const cut = t.slice(0, MAX_TITLE);
  return `${cut.slice(0, cut.lastIndexOf(" ") > 60 ? cut.lastIndexOf(" ") : MAX_TITLE)}...`;
};

const HEADER = `# Decision log index

Generated by \`npm run context:index\` from the files in this folder. Never edit it by hand (CONTRACTS.md 5.1):
add a decision with \`npm run decision:new -- --title "..."\`, which creates the file and rebuilds this list.
Not imported into every session on purpose: read or grep it when a task needs history.

`;

export function buildIndex(root = process.cwd()) {
  const dir = join(root, "context", "decisions");
  const lines = existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => /^\d{4}-\d{2}-\d{2}.*\.md$/.test(f))
        .sort()
        .map((f) => {
          const [, date] = f.match(/^(\d{4}-\d{2}-\d{2})/);
          const label = date.endsWith("-00") ? `${date.slice(0, 7)} (undated)` : date;
          const heading = readFileSync(join(dir, f), "utf8").split("\n")[0];
          const m = heading.match(/^#\s+\S+(?:\s+\(undated\))?\s+-\s+(.*)$/);
          return `- [${label}] ${shorten(m ? m[1] : heading.replace(/^#\s*/, ""))} - \`${f}\``;
        })
    : [];
  return `${HEADER}${lines.join("\n")}\n`;
}

/** For check-contracts: null when everything is in sync, otherwise the reason it is not. */
export function checkIndex(root = process.cwd()) {
  const indexPath = join(root, "context", "decisions", "INDEX.md");
  if (!existsSync(indexPath) || readFileSync(indexPath, "utf8") !== buildIndex(root)) return "context/decisions/INDEX.md is missing or out of date with the decision files. Run `npm run context:index` (never edit it by hand).";
  const stray = readFileSync(join(root, "CONTEXT.md"), "utf8").split("\n").findIndex((l) => /^- \*\*[A-Z][a-z]+ \d{1,2} 20\d\d/.test(l));
  if (stray !== -1) return `CONTEXT.md line ${stray + 1} is a dated entry. Entries are files under context/decisions/ (npm run decision:new), never lines appended to CONTEXT.md.`;
  return null;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const problem = checkIndex();
    if (problem) {
      console.error(problem);
      process.exit(1);
    }
    console.log("Decision index is up to date.");
  } else {
    writeFileSync(join(process.cwd(), "context", "decisions", "INDEX.md"), buildIndex());
    console.log(`context/decisions/INDEX.md rebuilt: ${buildIndex().split("\n").filter((l) => l.startsWith("- [")).length} decisions.`);
  }
}
